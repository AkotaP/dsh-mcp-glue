// Repository self-check: module syntax/imports, patch file shape, examples, and fixture JSON-RPC.
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { parse as parseYaml } from 'yaml';
import { pathToFileURL } from 'node:url';

const root = path.resolve(import.meta.dirname, '..');
const failures = [];
const check = async (name, fn) => {
  try { await fn(); console.log(`ok   ${name}`); }
  catch (error) { failures.push(`${name}: ${error.message}`); console.log(`FAIL ${name}\n     ${error.message}`); }
};
const read = file => fs.readFile(path.join(root, file), 'utf8');

await check('package.json declares the bundle patch and entry points', async () => {
  const manifest = JSON.parse(await read('package.json'));
  assert.equal(manifest.dsh?.bundle?.patch, './cordis.patch.yml');
  for (const file of [manifest.main, manifest.exports['.'], manifest.exports['./package.json']]) await fs.access(path.join(root, file));
  assert.equal(manifest.type, 'module');
});
await check('web client half declares the platform and a built bundle', async () => {
  const manifest = JSON.parse(await read('package.json'));
  assert.equal(manifest.dsh?.client?.platform, 'web');
  const clientExport = manifest.exports['./client'];
  assert.ok(clientExport, 'exports["./client"] is the only bundle-path source');
  const rel = typeof clientExport === 'string' ? clientExport : clientExport.default;
  const bundle = await read(rel);
  assert.ok(bundle.startsWith('// Generated by tools/build-client.mjs'), 'bundle is the generated artifact');
  assert.ok(bundle.includes('window.__ModuleLoader__.load('), 'bundle registers through the shell module loader');
  assert.ok(bundle.includes(`id: ${JSON.stringify(manifest.name)}`), 'bundle id must be the package name');
  // The host concatenates bundles as classic scripts: no ESM syntax may survive.
  assert.ok(!/^\s*(import|export)\s/m.test(bundle), 'bundle must not contain import/export statements');
  // The factory may only require baseline modules (or declared externals). Loading a
  // Harness Client package is out of bounds: those modules change without notice, and one
  // throwing import blanks the whole slot entry ("slot entry crashed").
  const baseline = new Set(['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client']);
  const externals = new Set(manifest.dsh?.client?.external ?? []);
  const required = [...bundle.matchAll(/require\(\s*['"]([^'"]+)['"]\s*\)/g)].map(match => match[1]);
  assert.ok(required.length > 0, 'the factory requires React from the baseline');
  for (const specifier of required) {
    assert.ok(!specifier.startsWith('@deepseek-ai/'), `the client half must not load the Harness package "${specifier}"`);
    assert.ok(baseline.has(specifier) || externals.has(specifier), `bundle requires non-baseline module "${specifier}"`);
  }
  assert.ok((manifest.dsh?.client?.inject ?? []).length > 0, 'dsh.client.inject must name the slot owners');
});
await check('the built bundle is in sync with src/client.js', async () => {
  const source = await read('src/client.js');
  const bundle = await read(JSON.parse(await read('package.json')).exports['./client'].default
    ?? JSON.parse(await read('package.json')).exports['./client']);
  for (const line of source.split('\n')) {
    const trimmed = line.trim();
    if (trimmed.length === 0) continue;
    assert.ok(bundle.includes(trimmed), `stale bundle: missing "${trimmed.slice(0, 60)}" — run pnpm run build`);
  }
});
await check('the package name is used consistently by host, bundle and client seat', async () => {
  const manifest = JSON.parse(await read('package.json'));
  const entry = await read('src/index.js');
  assert.match(entry, new RegExp(`export const packageName = ['"]${manifest.name}['"];`),
    'the host must resolve its own Loader entry by the package name');
  const bundle = await read('lib/client.js');
  assert.match(bundle, new RegExp(`key: ['"]${manifest.name}['"]`),
    'the preset manager seat must be keyed by the package name the host dispatches with');
});
await check('no runtime dependency on scope-sensitive @deepseek-ai modules', async () => {
  const manifest = JSON.parse(await read('package.json'));
  for (const field of ['dependencies', 'peerDependencies', 'optionalDependencies']) {
    for (const name of ['@deepseek-ai/dsh-scope', '@deepseek-ai/dsh-mcp-client', '@deepseek-ai/dsh-tools']) {
      assert.equal(manifest[field]?.[name], undefined, `${field} must not contain ${name}`);
    }
  }
  // Scope identity lives in module-private symbols: a second copy would turn scoped
  // registrations into global ones, so the bridge must come from the host loader.
  for (const file of ['src/index.js', 'src/runtime.js', 'src/load.js', 'src/normalize.js', 'src/presets.js']) {
    const source = await read(file);
    for (const name of ['@deepseek-ai/dsh-scope', '@deepseek-ai/dsh-mcp-client', '@deepseek-ai/dsh-tools', '@deepseek-ai/dsh-agent']) {
      assert.ok(!new RegExp(`from\\s+['"]${name}['"]`).test(source), `${file} must not statically import ${name}`);
    }
  }
});
await check('cordis.patch.yml inserts one loader entry with our package name', async () => {
  const patch = parseYaml(await read('cordis.patch.yml'));
  const rows = patch.flatMap(entry => entry.insert ?? []);
  assert.equal(rows.length, 1, 'exactly one inserted row');
  assert.equal(rows[0].id, 'workspace-mcp-glue');
  assert.equal(rows[0].name, JSON.parse(await read('package.json')).name);
});
await check('every source and test module imports cleanly', async () => {
  const files = ['src/index.js', 'src/presets.js', 'src/normalize.js', 'src/load.js', 'src/runtime.js'];
  for (const file of files) await import(pathToFileURL(path.join(root, file)).href);
  const plugin = await import(pathToFileURL(path.join(root, 'src/index.js')).href);
  assert.deepEqual(plugin.inject, ['agents', 'tools', 'fs', 'systemPrompt']);
  assert.equal(typeof plugin.Config, 'function');
  assert.equal(typeof plugin.apply, 'function');
});
await check('example patch parses and only uses supported config keys', async () => {
  const { Config } = await import(pathToFileURL(path.join(root, 'src/index.js')).href);
  const { liveConfig } = await import(pathToFileURL(path.join(root, 'src/config.js')).href);
  const entries = parseYaml(await read('examples/custom-presets.patch.yml'));
  const rows = [...entries, ...entries.flatMap(entry => entry.insert ?? [])].filter(row => row.id === 'workspace-mcp-glue');
  assert.equal(rows.length, 1);
  assert.equal(rows[0].name, undefined, 'the example patches the installed entry instead of inserting a second one');
  // Config fields the Host may rewrite are volatile, so they resolve to live references:
  // read them through the same unwrapped view the plugin itself uses.
  const resolved = liveConfig(new Config(rows[0].config));
  assert.equal(resolved.trustMode, 'manual');
  assert.deepEqual(resolved.workspaceAllowances.map(entry => entry.allowMcp), [['team-tools']], 'the example shows the per-workspace allowance');
  assert.equal(resolved.presets.at(-1).id, 'gemini');
  assert.ok(resolved.presets.some(preset => preset.id === 'team-tools' && preset.fields.command === 'executable'));
});
await check('bundled presets cover the documented project files', async () => {
  const { BUILTIN_PRESETS } = await import(pathToFileURL(path.join(root, 'src/presets.js')).href);
  const files = BUILTIN_PRESETS.flatMap(preset => preset.files);
  for (const expected of ['.mcp.json', '.vscode/mcp.json', '.codex/config.toml', '.cursor/mcp.json', '.gemini/settings.json']) assert.ok(files.includes(expected), expected);
});
await check('fixture server answers initialize and tools/list over stdio', async () => {
  const child = spawn(process.execPath, [path.join(root, 'test/fixtures/mcp-server.mjs'), 'smoke'], { stdio: ['pipe', 'pipe', 'inherit'] });
  const lines = [];
  child.stdout.setEncoding('utf8');
  child.stdout.on('data', chunk => lines.push(...chunk.split('\n').filter(Boolean)));
  const call = message => child.stdin.write(`${JSON.stringify({ jsonrpc: '2.0', ...message })}\n`);
  call({ id: 1, method: 'initialize', params: {} });
  call({ id: 2, method: 'tools/list' });
  for (let attempt = 0; lines.length < 2 && attempt < 200; attempt++) await new Promise(resolve => setTimeout(resolve, 25));
  child.kill();
  const replies = lines.map(line => JSON.parse(line));
  assert.equal(replies[0].result.serverInfo.name, 'fixture');
  assert.deepEqual(replies[1].result.tools.map(tool => tool.name), ['identity', 'blocked']);
});
await check('README documents every built-in preset and the trust default', async () => {
  const readme = await read('README.md');
  for (const token of ['.vscode/mcp.json', '.codex/config.toml', '.cursor/mcp.json', '.gemini/settings.json', 'trustMode', 'trustedWorkspaces', 'workspaceAllowances']) assert.ok(readme.includes(token), token);
});
if (failures.length) { console.error(`\n${failures.length} check(s) failed`); process.exit(1); }
console.log('\nall checks passed');
