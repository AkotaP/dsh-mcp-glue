// Wrap src/client.js into the browser bundle the host serves: the shell's module
// loader expects `window.__ModuleLoader__.load({ id, factory })`, whose factory
// returns the plugin exports through a CJS `require` limited to platform seeds.
import fs from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const manifest = JSON.parse(await fs.readFile(path.join(root, 'package.json'), 'utf8'));
const source = await fs.readFile(path.join(root, 'src/client.js'), 'utf8');
const indent = text => text.split('\n').map(line => (line.length === 0 ? line : `      ${line}`)).join('\n');
const bundle = `// Generated by tools/build-client.mjs from src/client.js — do not edit.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(manifest.name)},
  factory: (require) => {
    const module = { exports: {} };
${indent(source)}
    return module.exports;
  },
});
`;
await fs.mkdir(path.join(root, 'lib'), { recursive: true });
await fs.writeFile(path.join(root, 'lib/client.js'), bundle);
console.log(`built lib/client.js from src/client.js (${Buffer.byteLength(bundle)} bytes)`);
